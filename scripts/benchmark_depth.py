#!/usr/bin/env python3
"""
Benchmark script to measure execution time for different search depths.

Run this script BEFORE the competition to calibrate depth_benchmark.py
for your actual machine's performance.

Usage:
    uv run scripts/benchmark_depth.py
"""

import sys
import time
import json
from pathlib import Path

import matplotlib.pyplot as plt

# Add src to path
sys.path.insert(0, str(Path(__file__).parent.parent))

from src.tablut.cook_tablut.cook_tablut import CookedTablut
from src.tablut.common.enums.player import ROLE
from src.tablut.common.enums.chess import CHESS
from src.tablut.utils.logger import Logger


class DepthBenchmark:
    def __init__(self):
        self.logger = Logger("DepthBenchmark")
        self.results = {}

    def create_initial_board(self) -> list[list[CHESS]]:
        """Create initial Tablut board state (worst case: all pieces present)."""
        board = [[CHESS.EMPTY for _ in range(9)] for _ in range(9)]

        # White pieces (defenders)
        white_positions = [
            (0, 4), (1, 4), (2, 4), (3, 4), (5, 4), (6, 4), (7, 4), (8, 4),
            (4, 0), (4, 1), (4, 2), (4, 3), (4, 5), (4, 6), (4, 7), (4, 8),
        ]
        for r, c in white_positions:
            board[r][c] = CHESS.WHITE

        # Black pieces (attackers)
        black_positions = [
            (0, 3), (0, 4), (0, 5),
            (1, 4),
            (3, 0), (3, 8),
            (4, 0), (4, 8),
            (5, 4),
            (8, 3), (8, 4), (8, 5),
        ]
        for r, c in black_positions:
            board[r][c] = CHESS.BLACK

        # King (center)
        board[4][4] = CHESS.KING

        return board

    def benchmark_depth(self, depth: int, iterations: int = 3) -> float:
        """Measure average execution time for a specific depth."""
        cooked_tree = CookedTablut()
        board = self.create_initial_board()

        times = []
        for i in range(iterations):
            start = time.perf_counter()
            try:
                cooked_tree.get_next_movement(board, ROLE.WHITE, depth)
            except Exception as e:
                self.logger.error(f"  Iteration {i+1}: Error - {e}")
                return float('inf')

            elapsed = time.perf_counter() - start
            times.append(elapsed)
            self.logger.debug(f"  Iteration {i+1}: {elapsed:.3f}s")

        avg_time = sum(times) / len(times)
        return avg_time

    def update_benchmark_file(self) -> None:
        """Update depth_benchmark.py with new results."""
        benchmark_file = (
            Path(__file__).parent.parent / "src" / "tablut" / "game" / "depth_benchmark.py"
        )

        # Format the dictionary nicely
        dict_str = "{\n"
        for depth in sorted(self.results.keys()):
            dict_str += f"    {depth}: {self.results[depth]:.6f},\n"
        dict_str += "}"

        content = f'''"""Pre-computed depth benchmark table.

This table maps search depth to average execution time (in seconds).
Generated by: scripts/benchmark_depth.py

Before competition, run:
    uv run scripts/benchmark_depth.py

This will update the table below with actual performance metrics from your machine.
"""

# Placeholder values - run benchmark script to populate actual data
DEPTH_BENCHMARK = {dict_str}
'''

        benchmark_file.write_text(content)
        self.logger.info(f"Updated {benchmark_file}")

    def generate_chart(self) -> None:
        """Generate visualization charts."""
        depths = sorted(self.results.keys())
        times = [self.results[d] for d in depths]

        # Log scale chart
        fig, ax = plt.subplots(figsize=(12, 7))
        ax.plot(depths, times, marker='o', linewidth=2.5, markersize=8,
                color='#2E86AB', label='Execution Time')

        ax.grid(True, alpha=0.3, linestyle='--')
        ax.set_xlabel('Search Depth', fontsize=12, fontweight='bold')
        ax.set_ylabel('Execution Time (seconds)', fontsize=12, fontweight='bold')
        ax.set_title('Tablut Minimax with Alpha-Beta Pruning: Depth vs Time',
                     fontsize=14, fontweight='bold', pad=20)

        ax.set_xticks(depths)

        # Add annotations
        for depth, time in zip(depths, times):
            ax.annotate(f'{time:.3f}s',
                        xy=(depth, time),
                        xytext=(0, 8),
                        textcoords='offset points',
                        ha='center',
                        fontsize=9,
                        fontweight='bold')

        # Add safe budget lines
        safe_budgets = {
            '30s': 0.8 * (30 - 3),
            '60s': 0.8 * (60 - 3),
        }
        colors = {'30s': '#F77F00', '60s': '#D62828'}
        for timeout_label, safe_budget in safe_budgets.items():
            ax.axhline(y=safe_budget, color=colors[timeout_label],
                       linestyle='--', linewidth=1.5, alpha=0.7,
                       label=f'Safe budget ({timeout_label})')

        ax.set_ylim(bottom=0)
        ax.legend(loc='upper left', fontsize=11, framealpha=0.95)
        ax.set_yscale('log')

        chart_file = Path(__file__).parent / "depth_benchmark_chart_log.png"
        plt.savefig(chart_file, dpi=300, bbox_inches='tight')
        self.logger.info(f"Saved log-scale chart to {chart_file}")
        plt.close()

        # Linear scale chart
        fig, ax = plt.subplots(figsize=(12, 7))
        ax.plot(depths, times, marker='o', linewidth=2.5, markersize=8,
                color='#2E86AB', label='Execution Time')

        ax.grid(True, alpha=0.3, linestyle='--')
        ax.set_xlabel('Search Depth', fontsize=12, fontweight='bold')
        ax.set_ylabel('Execution Time (seconds)', fontsize=12, fontweight='bold')
        ax.set_title('Tablut Minimax with Alpha-Beta Pruning: Depth vs Time (Linear)',
                     fontsize=14, fontweight='bold', pad=20)
        ax.set_xticks(depths)

        for depth, time in zip(depths, times):
            ax.annotate(f'{time:.3f}s',
                        xy=(depth, time),
                        xytext=(0, 8),
                        textcoords='offset points',
                        ha='center',
                        fontsize=9,
                        fontweight='bold')

        for timeout_label, safe_budget in safe_budgets.items():
            ax.axhline(y=safe_budget, color=colors[timeout_label],
                       linestyle='--', linewidth=1.5, alpha=0.7,
                       label=f'Safe budget ({timeout_label})')

        ax.set_ylim(bottom=0)
        ax.legend(loc='upper left', fontsize=11, framealpha=0.95)

        chart_file = Path(__file__).parent / "depth_benchmark_chart_linear.png"
        plt.savefig(chart_file, dpi=300, bbox_inches='tight')
        self.logger.info(f"Saved linear-scale chart to {chart_file}")
        plt.close()

    def print_summary(self) -> None:
        """Print summary table and reference budgets."""
        self.logger.info("=" * 70)
        self.logger.info("DETAILED BENCHMARK TABLE")
        self.logger.info("=" * 70)
        self.logger.info(f"{'Depth':<8} {'Time (s)':<12} {'Growth Factor':<15}")
        self.logger.info("-" * 70)

        depths = sorted(self.results.keys())
        prev_time = self.results[depths[0]]
        for depth in depths:
            time = self.results[depth]
            if depth == depths[0]:
                growth = "—"
            else:
                growth = f"{time/prev_time:.2f}x"

            self.logger.info(f"{depth:<8} {time:<12.6f} {growth:<15}")
            prev_time = time

        self.logger.info("=" * 70)

        # Safe budget reference
        self.logger.info("REFERENCE: Safe Time Budgets")
        self.logger.info("-" * 70)
        for timeout in [30, 60, 90]:
            safe_budget = 0.8 * (timeout - 3)
            self.logger.info(
                f"  Timeout {timeout}s -> Available {timeout-3}s -> Safe budget {safe_budget:.1f}s"
            )

            best_depth = 3
            for depth in depths:
                if self.results[depth] < safe_budget:
                    best_depth = depth

            self.logger.info(f"    -> Maximum safe depth: {best_depth}")

    def run(self) -> None:
        """Execute benchmark and generate all outputs."""
        self.logger.info("=" * 70)
        self.logger.info("Tablut Depth Benchmark")
        self.logger.info("=" * 70)
        self.logger.info(
            "Ensure CookedTablut._is_valid_movement(), "
            "_get_game_status(), and _get_heuristic() are implemented."
        )

        # Test depths 1 to 12
        for depth in range(1, 13):
            self.logger.info(f"Benchmarking depth={depth}...")
            try:
                avg_time = self.benchmark_depth(depth, iterations=3)

                if avg_time == float('inf'):
                    self.logger.error(f"Depth {depth}: FAILED - stopping here")
                    break

                self.results[depth] = avg_time
                self.logger.info(f"Average: {avg_time:.3f}s")

                # Safety check: if taking too long, stop
                if avg_time > 30:
                    self.logger.warning(
                        f"Depth {depth} exceeded 30s, stopping benchmarks"
                    )
                    break

            except KeyboardInterrupt:
                self.logger.error("Benchmark interrupted by user")
                sys.exit(1)
            except Exception as e:
                self.logger.error(f"Error at depth {depth}: {e}")
                break

        if self.results:
            # Save results to JSON
            json_file = Path(__file__).parent / "depth_benchmark.json"
            with open(json_file, "w") as f:
                json.dump(self.results, f, indent=2)
            self.logger.info(f"Saved results to {json_file}")

            # Update Python benchmark file
            self.update_benchmark_file()

            # Generate charts
            self.logger.info("Generating charts...")
            self.generate_chart()

            # Print summary
            self.print_summary()

            self.logger.info("=" * 70)
            self.logger.info("Benchmark complete")
        else:
            self.logger.error("No benchmark results collected")
            sys.exit(1)


if __name__ == "__main__":
    benchmark = DepthBenchmark()
    benchmark.run()

